import Constants from "expo-constants";
import * as Linking from "expo-linking";
import * as SecureStore from "expo-secure-store";
import * as ReactNative from "react-native";

// Extract scheme from bundle ID (last segment timestamp, prefixed with "manus").
const bundleId = "space.manus.geteven.t063584009839075";
const timestamp = bundleId.split(".").pop()?.replace(/^t/, "") ?? "";
const schemeFromBundleId = `manus${timestamp}`;

const extra = (Constants.expoConfig?.extra ?? {}) as Record<
  string,
  string | undefined
>;

const env = {
  apiBaseUrl: extra.apiBaseUrl ?? process.env.EXPO_PUBLIC_API_BASE_URL ?? "",
  deepLinkScheme: schemeFromBundleId,
};

export const API_BASE_URL = env.apiBaseUrl;

/**
 * Get the API base URL, deriving from the paired Preview hostname when the
 * public runtime did not inject an explicit value.
 */
export function getApiBaseUrl(): string {
  if (API_BASE_URL) return API_BASE_URL.replace(/\/$/, "");

  if (
    ReactNative.Platform.OS === "web" &&
    typeof window !== "undefined" &&
    window.location
  ) {
    const { protocol, hostname } = window.location;
    const apiHostname = hostname.replace(/^8081-/, "3000-");
    if (apiHostname !== hostname) return `${protocol}//${apiHostname}`;
  }

  return "";
}

export const SESSION_TOKEN_KEY = "app_session_token";
export const USER_INFO_KEY = "manus-runtime-user-info";
export const OAUTH_VERIFIER_KEY = "manus-oauth-verifier";

type OAuthBeginResponse = {
  authorizationUrl?: unknown;
  verifier?: unknown;
};

function managedExpoGoRedirectUri(): string | null {
  if (Constants.appOwnership !== "expo") return null;
  try {
    const url = new URL(Constants.linkingUri);
    if (url.protocol !== "exp:" && url.protocol !== "exps:") return null;
    url.pathname = "/--/oauth/callback";
    url.search = "";
    url.hash = "";
    return url.toString();
  } catch {
    return null;
  }
}

/**
 * Get the only callback URI this app can use. Web callback terminates at the
 * configured API; a build uses the configured application scheme; Expo Go uses
 * its current managed host callback.
 */
export function getRedirectUri(): string {
  if (ReactNative.Platform.OS === "web") {
    return `${getApiBaseUrl()}/api/oauth/callback`;
  }

  return (
    managedExpoGoRedirectUri() ??
    Linking.createURL("/oauth/callback", {
      scheme: env.deepLinkScheme,
    })
  );
}

async function beginOAuthLogin(): Promise<{
  authorizationUrl: string;
  verifier?: string;
}> {
  const baseUrl = getApiBaseUrl();
  if (!baseUrl && ReactNative.Platform.OS !== "web") {
    throw new Error("Authentication service is unavailable");
  }

  const response = await fetch(`${baseUrl}/api/oauth/begin`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    credentials: "include",
    body: JSON.stringify({ redirectUri: getRedirectUri() }),
  });
  if (!response.ok) throw new Error("Unable to start secure sign-in");

  const payload = (await response.json()) as OAuthBeginResponse;
  if (
    typeof payload.authorizationUrl !== "string" ||
    !payload.authorizationUrl
  ) {
    throw new Error("Unable to start secure sign-in");
  }
  if (
    ReactNative.Platform.OS !== "web" &&
    typeof payload.verifier !== "string"
  ) {
    throw new Error("Unable to start secure sign-in");
  }

  return {
    authorizationUrl: payload.authorizationUrl,
    verifier:
      typeof payload.verifier === "string" ? payload.verifier : undefined,
  };
}

/**
 * Start the real Manus OAuth flow. State and verifier are generated by the
 * server; native stores only the verifier in SecureStore until the callback.
 */
export async function startOAuthLogin(): Promise<string | null> {
  const { authorizationUrl, verifier } = await beginOAuthLogin();

  if (ReactNative.Platform.OS === "web") {
    if (typeof window !== "undefined") window.location.assign(authorizationUrl);
    return null;
  }

  if (!verifier || !(await Linking.canOpenURL(authorizationUrl))) {
    throw new Error("Unable to open secure sign-in");
  }

  await SecureStore.setItemAsync(OAUTH_VERIFIER_KEY, verifier);
  try {
    await Linking.openURL(authorizationUrl);
  } catch {
    await SecureStore.deleteItemAsync(OAUTH_VERIFIER_KEY);
    throw new Error("Unable to open secure sign-in");
  }

  return null;
}
